param(
  [string]$Root = '',
  [string]$ServiceName = 'DSH-WireGuard-Control',
  [string]$NodePath = '',
  [string]$DshHome = ''
)

$ErrorActionPreference = 'Stop'
if ([string]::IsNullOrWhiteSpace($Root)) {
  $Root = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
}
$Root = (Resolve-Path $Root).Path
if ([string]::IsNullOrWhiteSpace($NodePath)) {
  $NodePath = (Get-Command node.exe -ErrorAction SilentlyContinue).Source
}
if ([string]::IsNullOrWhiteSpace($NodePath) -or -not (Test-Path $NodePath)) {
  throw 'node.exe not found; pass -NodePath <path> or put node on PATH.'
}
if ([string]::IsNullOrWhiteSpace($DshHome)) {
  $DshHome = Join-Path $env:USERPROFILE '.dsh'
}
$envFile = Join-Path $Root 'control-service.env'
@(
  '# Generated by install-control-service.ps1',
  "DSH_HOME=$DshHome",
  "DSH_WIREGUARD_NODE=$NodePath"
) | Set-Content -LiteralPath $envFile -Encoding utf8
$source = Join-Path $PSScriptRoot 'DshWireGuardControlService.cs'
$exe = Join-Path $Root 'dsh-wireguard-control-service.exe'
$csc = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
if (-not (Test-Path $csc)) { $csc = Join-Path $env:WINDIR 'Microsoft.NET\Framework\v4.0.30319\csc.exe' }
if (-not (Test-Path $csc)) { throw 'Cannot find the .NET Framework C# compiler (csc.exe).' }

Write-Host "Compiling $exe"
& $csc /nologo /target:exe /out:$exe /r:System.ServiceProcess.dll $source
if ($LASTEXITCODE -ne 0) { throw "csc failed with exit code $LASTEXITCODE" }

$existing = Get-Service -Name $ServiceName -ErrorAction SilentlyContinue
if ($existing) {
  Write-Host "Removing existing service $ServiceName"
  Stop-Service -Name $ServiceName -Force -ErrorAction SilentlyContinue
  & sc.exe delete $ServiceName 2>$null | Out-Null
  Start-Sleep -Seconds 2
}

Write-Host "Creating service $ServiceName"
$binPath = '"' + $exe + '"'
& sc.exe create $ServiceName binPath= $binPath start= auto DisplayName= 'DSH WireGuard Control' | Out-Null
if ($LASTEXITCODE -ne 0) { throw "sc create failed with exit code $LASTEXITCODE" }
& sc.exe description $ServiceName 'Standalone WireGuard control panel on 51821' | Out-Null
& sc.exe failure $ServiceName reset= 86400 actions= restart/5000/restart/10000/restart/30000 | Out-Null
& sc.exe start $ServiceName | Out-Null
if ($LASTEXITCODE -ne 0) { throw "sc start failed with exit code $LASTEXITCODE" }

$deadline = (Get-Date).AddSeconds(60)
$healthy = $false
while ((Get-Date) -lt $deadline) {
  try {
    $health = Invoke-WebRequest -Uri 'http://127.0.0.1:51821/api/dsh-wireguard/health' -UseBasicParsing -TimeoutSec 3
    if ($health.StatusCode -eq 200) { Write-Host $health.Content; $healthy = $true; break }
  } catch { }
  Start-Sleep -Seconds 2
}
Get-Service -Name $ServiceName | Select-Object Name, Status, StartType
if (-not $healthy) {
  Get-Content (Join-Path $Root 'control-service.log') -Tail 60 -ErrorAction SilentlyContinue
  throw 'Control service did not become healthy on 51821.'
}
Write-Host 'Control service is running on 51821.'
